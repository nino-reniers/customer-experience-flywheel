'use strict';

// Generates the example-content SQL files. The check rows in 002 are computed
// by running the real screening engine (lib/checks.js) over the example text,
// so the demo entries show exactly what the engine produces.
// IDs are predicted from insert order on a fresh database (identity starts at 1).

const fs = require('fs');
const path = require('path');
const data = require('./example-data');
const { runValidity, runOverlap } = require('../lib/checks');

const S = s => "'" + String(s == null ? '' : s).replace(/'/g, "''") + "'";
const J = o => S(JSON.stringify(o));

const reasonIds = data.reasons.map((r, i) => i + 1);
const hypIds = data.hypotheses.map((h, i) => i + 1);

let out = [
  '-- Example content for the Customer Experience Library.',
  '-- Every row is flagged is_example = true so it is clearly demo content.',
  '-- Generated by seed/generate-sql.js — edit seed/example-data.js and regenerate.'
];
data.reasons.forEach(r => {
  out.push('insert into churn_reasons (title, category, description, evidence_source, affected_segment, flywheel_driver, flywheel_subdriver, is_example) values (' +
    S(r.title) + ', ' + S(r.category) + ', ' + S(r.description) + ', ' + S(r.evidence_source || '') + ', ' + S(r.affected_segment || '') + ', ' + S(r.driver || '') + ', ' + S(r.subdriver || '') + ', true);');
});
data.hypotheses.forEach((h, i) => {
  out.push('insert into hypotheses (churn_reason_id, title, if_we, then_outcome, because_mechanism, target_segment, primary_metric, success_criterion, status, is_example) values (' +
    reasonIds[h.reasonIndex] + ', ' + S(h.title) + ', ' + S(h.if_we) + ', ' + S(h.then_outcome) + ', ' + S(h.because_mechanism) + ', ' +
    S(h.target_segment) + ', ' + S(h.primary_metric) + ', ' + S(h.success_criterion || '') + ', ' + S(h.status) + ', true);');
  const impact = h.impact;
  if (impact) {
    out.push('insert into impact_sizings (hypothesis_id, affected_customers, expected_lift, revenue_at_stake, confidence, assumptions, method) values (' +
      hypIds[i] + ', ' + S(impact.affected_customers || '') + ', ' + S(impact.expected_lift || '') + ', ' + S(impact.revenue_at_stake || '') + ', ' +
      S(impact.confidence || 'medium') + ', ' + S(impact.assumptions || '') + ', ' + S(impact.method || '') + ');');
  }
  (h.necessities || []).forEach(n => {
    out.push('insert into technical_necessities (hypothesis_id, requirement_type, description, effort, dependencies, owning_team) values (' +
      hypIds[i] + ', ' + S(n.type || 'other') + ', ' + S(n.description || '') + ', ' + S(n.effort || 'M') + ', ' + S(n.dependencies || '') + ', ' + S(n.owning_team || '') + ');');
  });
});
fs.writeFileSync(path.join(__dirname, '001_examples.sql'), out.join('\n') + '\n');

const asCandidates = data.hypotheses.map((h, i) => ({
  id: hypIds[i], title: h.title, if_we: h.if_we, because_mechanism: h.because_mechanism,
  primary_metric: h.primary_metric, churn_reason_id: reasonIds[h.reasonIndex], status: h.status
}));
let cout = [
  '-- Example check results: generated by running the real screening engine over the example content.',
  '-- Hypothesis ids follow the insert order of 001_examples.sql on a fresh database.'
];
data.hypotheses.forEach((h, i) => {
  const validity = runValidity(h);
  const overlap = runOverlap(Object.assign({ id: hypIds[i], churn_reason_id: reasonIds[h.reasonIndex] }, h), asCandidates);
  cout.push('insert into hypothesis_checks (hypothesis_id, check_type, score, result) values (' + hypIds[i] + ", 'validity', " + validity.score + ', ' + J(validity) + '::jsonb);');
  cout.push('insert into hypothesis_checks (hypothesis_id, check_type, score, result) values (' + hypIds[i] + ", 'overlap', " + Math.round(overlap.score * 100) + ', ' + J(overlap) + '::jsonb);');
});
fs.writeFileSync(path.join(__dirname, '002_example_checks.sql'), cout.join('\n') + '\n');
console.log('Wrote 001_examples.sql and 002_example_checks.sql');
