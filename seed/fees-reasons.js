const S = s => "'" + String(s == null ? '' : s).replace(/'/g, "''") + "'";
// E-string helper: keeps every INSERT on one physical line (db sql takes one
// statement per argument) while storing real newlines between sentences.
const SE = s => "E'" + String(s == null ? '' : s).replace(/\\/g, '\\\\').replace(/'/g, "''").replace(/\n/g, '\\n') + "'";

let out = ['-- Curated leaving-reasons for Price and discounts / Fees (user-provided, with source links).', '-- Generated by seed/fees-reasons.js.'];
for (const r of REASONS) {
  const sources = r.cites.map(n => ({ label: String(n), url: SRC[n] }));
  out.push('insert into leaving_reasons (flywheel_driver, flywheel_subdriver, flywheel_type, title, body, sources) values ' +
    "('Price and discounts', 'Fees', null, " + S(r.title) + ', ' + SE(r.sentences.join('\n')) + ', ' + S(JSON.stringify(sources)) + '::jsonb);');
}
fs.writeFileSync(path.join(__dirname, '003_fees_reasons.sql'), out.join('\n') + '\n');
console.log('Wrote 003_fees_reasons.sql with ' + REASONS.length + ' reasons');
